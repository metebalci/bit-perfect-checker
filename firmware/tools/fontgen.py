"""Turns fixed-width BDF fonts into C arrays for the firmware's display.

    python3 -I fontgen.py --out <dir> <name>=<file.bdf> [<name>=<file.bdf> ...]

writes <dir>/fonts.h and <dir>/fonts.c with one font_t per argument, named
font_<name>, holding the printable ASCII characters 0x20 to 0x7E. A glyph is
its rows top to bottom, each row's pixels left to right, the most significant
bit first, each row padded to whole bytes (BDF's own BITMAP layout). The
output depends only on the BDF files' contents and the arguments, so a re-run
gives the same bytes.

CMake runs this at build time for boards with a display; the fonts come from
the Spleen submodule (lib/spleen, BSD-2-Clause).
"""

import argparse
import os
import sys

FIRST = 0x20
LAST = 0x7E


class BdfError(Exception):
    pass


def parse_bdf(path):
    """Returns (width, height, glyphs, info) for a font whose glyphs all fill
    its bounding box; glyphs maps an encoding to its rows as integers."""
    with open(path, encoding="ascii") as f:
        lines = f.read().splitlines()
    width = height = None
    info = {}
    glyphs = {}
    i = 0
    while i < len(lines):
        words = lines[i].split()
        i += 1
        if not words:
            continue
        key = words[0]
        if key == "FONTBOUNDINGBOX":
            width, height = int(words[1]), int(words[2])
            info["bbox"] = tuple(int(w) for w in words[1:5])
        elif key in ("FAMILY_NAME", "FONT_VERSION"):
            info[key] = " ".join(words[1:]).strip('"')
        elif key == "COMMENT" and ("Copyright" in words or "SPDX-License-Identifier:" in words):
            info.setdefault("notice", []).append(" ".join(w for w in words[1:] if w != "*"))
        elif key == "STARTCHAR":
            encoding = bbx = None
            while True:
                if i >= len(lines):
                    raise BdfError(f"{path}: glyph without ENDCHAR")
                words = lines[i].split()
                i += 1
                if words and words[0] == "ENCODING":
                    encoding = int(words[1])
                elif words and words[0] == "BBX":
                    bbx = tuple(int(w) for w in words[1:5])
                elif words and words[0] == "BITMAP":
                    break
            if encoding is None or bbx is None:
                raise BdfError(f"{path}: glyph without ENCODING or BBX")
            rows = []
            while i < len(lines) and lines[i].strip() != "ENDCHAR":
                rows.append(int(lines[i].strip(), 16))
                i += 1
            i += 1
            if FIRST <= encoding <= LAST:
                if bbx != info.get("bbox"):
                    raise BdfError(f"{path}: glyph {encoding:#x} has BBX {bbx}, "
                                   f"not the font's bounding box {info.get('bbox')}")
                if len(rows) != height:
                    raise BdfError(f"{path}: glyph {encoding:#x} has {len(rows)} rows, not {height}")
                glyphs[encoding] = rows
    if width is None:
        raise BdfError(f"{path}: no FONTBOUNDINGBOX")
    missing = [c for c in range(FIRST, LAST + 1) if c not in glyphs]
    if missing:
        raise BdfError(f"{path}: no glyph for {', '.join(hex(c) for c in missing)}")
    return width, height, glyphs, info


def glyph_bytes(rows, width):
    """A glyph's rows as bytes, each row in (width + 7) // 8 bytes."""
    row_bytes = (width + 7) // 8
    out = bytearray()
    for row in rows:
        out += row.to_bytes(row_bytes, "big")
    return bytes(out)


def describe(path, info):
    family = info.get("FAMILY_NAME", "")
    version = info.get("FONT_VERSION", "")
    return " ".join(w for w in (os.path.basename(path), f"({family} {version})".strip()) if w != "()")


HEADER = """\
// Generated by firmware/tools/fontgen.py; do not edit.

#ifndef FONTS_H
#define FONTS_H

#include <stdint.h>

// A fixed-width bitmap font for the characters first to first + count - 1.
// Each glyph is height rows of width pixels, top to bottom, each row left to
// right with the most significant bit first and padded to whole bytes;
// glyph_bytes bytes per glyph, one glyph after the other.
typedef struct {
  uint8_t width;
  uint8_t height;
  uint8_t first;
  uint8_t count;
  uint16_t glyph_bytes;
  const uint8_t *bits;
} font_t;

// The glyph of character c, or that of '?' if the font has none.
static inline const uint8_t *font_glyph(const font_t *font, char c) {
  uint8_t i = (uint8_t) c;
  if (i < font->first || i - font->first >= font->count) {
    i = '?';
  }
  return font->bits + (uint32_t) (i - font->first) * font->glyph_bytes;
}

"""


def generate(fonts):
    """fonts: list of (name, path). Returns the texts of fonts.h and fonts.c."""
    h = [HEADER]
    c = ["// Generated by firmware/tools/fontgen.py; do not edit.\n"]
    for name, path in fonts:
        info = parse_bdf(path)[3]
        c.append(f"// font_{name}: {describe(path, info)}\n")
        for line in info.get("notice", []):
            c.append(f"//   {line}\n")
    c.append("\n#include \"fonts.h\"\n")
    for name, path in fonts:
        width, height, glyphs, info = parse_bdf(path)
        per_glyph = (width + 7) // 8 * height
        count = LAST - FIRST + 1
        h.append(f"extern const font_t font_{name};\n")
        c.append(f"\nstatic const uint8_t font_{name}_bits[{count * per_glyph}] = {{\n")
        for code in range(FIRST, LAST + 1):
            data = glyph_bytes(glyphs[code], width)
            label = {0x27: "'\\''", 0x5C: "'\\\\'"}.get(code, f"'{chr(code)}'")
            c.append(f"  // {code:#04x} {label}\n")
            for k in range(0, len(data), 16):
                c.append("  " + " ".join(f"0x{b:02x}," for b in data[k:k + 16]) + "\n")
        c.append("};\n")
        c.append(f"\nconst font_t font_{name} = {{\n"
                 f"  .width = {width},\n"
                 f"  .height = {height},\n"
                 f"  .first = {FIRST:#04x},\n"
                 f"  .count = {count},\n"
                 f"  .glyph_bytes = {per_glyph},\n"
                 f"  .bits = font_{name}_bits,\n"
                 f"}};\n")
    h.append("\n#endif\n")
    return "".join(h), "".join(c)


def write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "wb") as f:
        f.write(text.encode("ascii"))
    os.replace(tmp, path)


def main(argv=None):
    ap = argparse.ArgumentParser(description="BDF fonts to C arrays")
    ap.add_argument("--out", required=True, help="folder for fonts.h and fonts.c")
    ap.add_argument("fonts", nargs="+", metavar="NAME=FILE.bdf")
    args = ap.parse_args(argv)
    fonts = []
    for spec in args.fonts:
        name, sep, path = spec.partition("=")
        if not sep or not ("font_" + name).isidentifier():
            ap.error(f"expected NAME=FILE.bdf where font_NAME is a C identifier, got {spec!r}")
        fonts.append((name, path))
    try:
        h, c = generate(fonts)
    except (BdfError, OSError, ValueError) as e:
        print(f"fontgen: {e}", file=sys.stderr)
        return 1
    os.makedirs(args.out, exist_ok=True)
    write(os.path.join(args.out, "fonts.h"), h)
    write(os.path.join(args.out, "fonts.c"), c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
